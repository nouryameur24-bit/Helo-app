const CS: R = ['caution','safe','safe','caution'];

function f(ni: string, n: string, r: R, d: string, conf: 'high'|'medium'|'low' = 'high'): PreComputedIngredient {
  return ing(ni, n, 'food', r, d, 'efsa', conf);
}

